#!/usr/bin/env node
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUTPUT = join(ROOT, 'docs', 'demo-evidence.md');
const temp = mkdtempSync(join(tmpdir(), 'web-app-security-demo-evidence-'));
const demoOutput = join(temp, 'demo-output');

try {
  const result = spawnSync(process.execPath, [join(ROOT, 'scripts', 'demo.mjs'), '--out', demoOutput], {
    cwd: ROOT, encoding: 'utf8', timeout: 30000, env: { ...process.env, SOURCE_DATE_EPOCH: '0' },
  });
  if (result.status !== 0) throw new Error(result.stderr || result.stdout || 'demo failed');
  const facts = JSON.parse(readFileSync(join(demoOutput, 'demo-result.json'), 'utf8'));
  const patch = readFileSync(join(demoOutput, 'hardening.patch'), 'utf8').trim();
  const rendered = `# Generated source demo evidence

<!-- Generated by scripts/generate-demo-evidence.mjs. Do not edit by hand. -->

The input is an owned local Node.js fixture. The demo reads source, sends no network request and
does not execute project dependencies. A source match remains a \`suspected\` lead.

| Input | Finding | Evidence state | Proposal | Security retest | Functional retest |
|---|---|---|---|---|---|
| \`${facts.input}\` | ${facts.before.technicalTerm} | \`${facts.before.state}\` | ${facts.proposal.summary} | \`${facts.securityRetest.baselineState}\` | \`${facts.functionalRetest.status}\` |

## Plain-language result

${facts.before.plainLanguage}

Possible consequence: ${facts.before.consequence}

Evidence boundary: ${facts.before.evidenceBoundary}

Possible side effect: ${facts.proposal.sideEffects.join(' ')}

## Reviewable proposal

\`\`\`diff
${patch}
\`\`\`

The patch is not proof of a fix. The compatible source retest records the original finding as
\`${facts.securityRetest.baselineState}\`; the separate fixed-input product test records:
\`${facts.functionalRetest.evidence}\`.

Run \`npm run demo -- --out ./demo-output\` for the v3 JSON/Markdown before and after reports,
patch, structured facts and functional-test evidence.
`;
  if (process.argv.includes('--check')) {
    if (!existsSync(OUTPUT) || readFileSync(OUTPUT, 'utf8') !== rendered) {
      throw new Error('demo evidence is stale; run node scripts/generate-demo-evidence.mjs');
    }
    console.log('demo evidence current: source lead, proposal, side effect and dual retest');
  } else {
    mkdirSync(join(ROOT, 'docs'), { recursive: true });
    writeFileSync(OUTPUT, rendered);
    console.log(OUTPUT);
  }
} finally {
  rmSync(temp, { recursive: true, force: true });
}
